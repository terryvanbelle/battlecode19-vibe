#!/usr/bin/env node
// Build engine19.js for the replay viewer: the pinned engine's game.js, action_record.js, specs.json and
// mersenne-twister wrapped in a tiny CommonJS loader, exposing window.BC19Engine = {Game, SPECS, ActionRecord}.
// No bot code and no network code is included (game.js only re-simulates the recorded actions).
//   node build_engine.js <engine node_modules dir> <out engine19.js>
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const [nm, out] = process.argv.slice(2);
if (!nm || !out) { console.error('usage: build_engine.js <node_modules dir> <out.js>'); process.exit(2); }
const mods = {
  './specs': ['json', path.join(nm, 'bc19', 'specs.json')],
  './action_record': ['js', path.join(nm, 'bc19', 'action_record.js')],
  'mersenne-twister': ['js', path.join(nm, 'mersenne-twister', 'src', 'mersenne-twister.js')],
  './game': ['js', path.join(nm, 'bc19', 'game.js')],
};
const ver = JSON.parse(fs.readFileSync(path.join(nm, 'bc19', 'package.json'), 'utf8')).version;
let s = `// Generated by tools/galaxy19/viewer/build_engine.js from bc19 ${ver} (game.js, action_record.js, specs.json)\n` +
  `// and mersenne-twister. Re-simulation only.\n(function () {\n// sloppy mode on purpose: game.js uses octal escapes, which strict mode rejects\nvar defs = {}, cache = {};\n` +
  `function req(n) { if (cache[n]) return cache[n].exports; var m = cache[n] = {exports: {}}; ` +
  `if (!defs[n]) throw new Error('no module ' + n); defs[n](m, m.exports, req); return m.exports; }\n`;
for (const [name, [kind, file]] of Object.entries(mods)) {
  const src = fs.readFileSync(file, 'utf8');
  const h = crypto.createHash('sha256').update(src).digest('hex').slice(0, 16);
  s += `// ${path.relative(nm, file)} sha256:${h}\n`;
  if (kind === 'json') s += `defs[${JSON.stringify(name)}] = function (module) { module.exports = ${src.trim()}; };\n`;
  else s += `defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${src}\n};\n`;
}
s += `window.BC19Engine = {Game: req('./game'), SPECS: req('./specs'), ActionRecord: req('./action_record'), version: ${JSON.stringify(ver)}};\n})();\n`;
fs.writeFileSync(out, s);
console.log(`wrote ${out} (${s.length} bytes, bc19 ${ver})`);
