[Install]
WantedBy=multi-user.target
EOF
  cat > "/etc/systemd/system/$U_RELAY" <<EOF
[Unit]
Description=bc19 galaxy replica: loopback relay (saturn reports, Cloud Tasks) to siarnaq on 127.0.0.1:$PORT
$head

[Service]
Type=simple
$(unit_common "" "$HOMED")
WorkingDirectory=$HOMED
$nftcheck
ExecStart=/usr/bin/python3 $OPT/galaxy19/relay.py serve
