  # the official 2019 visualizer class, its unit images and pixi.js 4.8.9, each checked against viewer/PINS.json
  "$OPT/runtime/bin/node" "$OPT/galaxy19/viewer/build_official.js" "$VIEWER_IN/battlecode19" "$VIEWER_IN/pixi-4.8.9/pixi.min.js" "$v.new"
  chown -R root:caddy "$v.new"; chmod -R u=rwX,g=rX,o= "$v.new"
  rm -rf "$v.old"; [ -e "$v" ] && mv "$v" "$v.old"; mv "$v.new" "$v"; rm -rf "$v.old"
}

frontend_step () {
  say "frontend: copy of $FRONT23 patched for episode bc19 (default episode, Replay! link to /viewer/)"
  local dst="$WWW/frontend"
  if [ ! -f "$FRONT23/index.html" ]; then
    # the 2023 replica's copy is gone (retired): keep the patched copy already installed here
    [ -f "$dst/index.html" ] || die "no built frontend at $FRONT23 and none installed at $dst"
    say "frontend: $FRONT23 absent; keeping the installed $dst"; return 0
  fi
  rm -rf "$dst.new"; cp -r "$FRONT23" "$dst.new"
  python3 - "$dst.new" <<'PY'
import glob, os, sys
d = sys.argv[1]
js = [p for p in glob.glob(os.path.join(d, 'assets', 'index-*.js'))]
assert len(js) == 1, js
s = open(js[0]).read()
for old, new in (('Qm="bc23"', 'Qm="bc19"'), ('case"bc23":return`/viewer/visualizer.html', 'case"bc19":return`/viewer/visualizer.html')):
    n = s.count(old)
    if n != 1:
        sys.exit(f'frontend patch: {old!r} found {n} times (expected 1)')
    s = s.replace(old, new)
open(js[0], 'w').write(s)
for m in glob.glob(os.path.join(d, 'assets', '*.map')):
    os.unlink(m)                       # the source map no longer matches the patched bundle
with open(os.path.join(d, 'REPLICA_BUILD.txt'), 'a') as fh:
    fh.write('bc19 replica: default episode bc19, Replay! link for bc19 -> /viewer/visualizer.html (galaxy-setup.sh frontend)\n')
print('patched', os.path.basename(js[0]))
PY
  python3 "$OPT/galaxy19/frontend_check.py" "$dst.new" > "$ETC/frontend-check.txt" || { tail -5 "$ETC/frontend-check.txt"; die "frontend check failed ($ETC/frontend-check.txt)"; }
  tail -3 "$ETC/frontend-check.txt"
  chown -R root:caddy "$dst.new"; chmod -R u=rwX,g=rX,o= "$dst.new"
  rm -rf "$dst.old"; [ -e "$dst" ] && mv "$dst" "$dst.old"; mv "$dst.new" "$dst"; rm -rf "$dst.old"
}

hostname_step () {
  local ip; ip=$(curl -s -m 5 -H 'Metadata-Flavor: Google' \
    http://169.254.169.254/computeMetadata/v1/instance/network-interfaces/0/access-configs/0/external-ip || true)
  [[ $ip =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "no external IP from the metadata server"
  echo "${ip//./-}.sslip.io" > "$ETC/hostname.new"; chmod 0644 "$ETC/hostname.new"
  if ! cmp -s "$ETC/hostname.new" "$ETC/hostname"; then mv -f "$ETC/hostname.new" "$ETC/hostname"; say "host: $(cat "$ETC/hostname")"
  else rm -f "$ETC/hostname.new"; fi
}

print_site () {  # $1 host, $2 bcrypt hash
  cat <<EOF
# The bc19 galaxy replica. Generated by $LIB/galaxy-setup.sh site; imported from $CADDYFILE. Doc: $DOC
$1 {
	log {
		output file /var/log/caddy/galaxy19-access.log {
			roll_size 10MiB
			roll_keep 3
		}
	}
	header {
		-Server
		Strict-Transport-Security "max-age=31536000"
		X-Content-Type-Options nosniff
		X-Frame-Options SAMEORIGIN
		Referrer-Policy same-origin
		Content-Security-Policy "$CSP"
	}
	encode zstd gzip
	@bearer_api {
		path /api/*
		not path /api/token/* /api/user/password_reset/*
		header_regexp Authorization ^Bearer\s+[A-Za-z0-9._~+/=-]+$
	}
	handle @bearer_api {
		reverse_proxy 127.0.0.1:$PORT
	}
	handle /manifest.json {
		root * $WWW/frontend
		file_server
	}
	handle {
		basic_auth {
			owner $2
		}
		@backend path /api/* /admin /admin/*
		handle @backend {
			reverse_proxy 127.0.0.1:$PORT {
				header_up -Authorization
				@siarnaq_401 status 401
				handle_response @siarnaq_401 {
					header -WWW-Authenticate
					copy_response 403
				}
			}
		}
		handle_path /static/* {
			root * $WWW/static
			file_server
		}
		handle_path /storage/* {
			root * $WWW/storage
			header Cache-Control "private, no-cache"
			file_server {
				hide .tmp-*
			}
		}
		handle_path /viewer/* {
			root * $WWW/viewer
			file_server
		}
		handle {
			root * $WWW/frontend
			try_files {path} /index.html
			file_server
		}
	}
}
EOF
}

ensure_import () {  # idempotent; also run before every start/reload of the shared Caddy (drop-in), since the 2023
                    # render rewrites the Caddyfile without this line
  [ -f "$CADDY_SITE" ] || return 0
  grep -qxF "import $CADDY_SITE" "$CADDYFILE" || printf '\n# bc19 galaxy replica (%s)\nimport %s\n' "$DOC" "$CADDY_SITE" >> "$CADDYFILE"
}

site_step () {
  [ -s "$ETC/hostname" ] || hostname_step
  local host="$SITE_PREFIX$(cat "$ETC/hostname")"
  say "Caddy: site https://$host/ (import in the shared Caddyfile; drop-in keeps it across 2023 re-renders)"
  print_site "$host" "$(cat "$ETC/owner.bcrypt")" > "$CADDY_SITE.new"
  chown root:caddy "$CADDY_SITE.new"; chmod 0640 "$CADDY_SITE.new"; mv -f "$CADDY_SITE.new" "$CADDY_SITE"
  ensure_import
  install -d -m 0755 "/etc/systemd/system/$CADDY_UNIT.d"
  cat > "/etc/systemd/system/$CADDY_UNIT.d/bc19-galaxy.conf" <<EOF
# bc19 galaxy replica: re-add the import of $CADDY_SITE if a 2023 render dropped it. Doc: $DOC
[Service]
ExecStartPre=+$LIB/galaxy-setup.sh ensure-import
ExecReload=
ExecReload=+$LIB/galaxy-setup.sh ensure-import
ExecReload=/usr/local/bin/caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile --force
EOF
  systemctl daemon-reload
  (cd /var/lib/caddy && runuser -u caddy -- env HOME=/var/lib/caddy /usr/local/bin/caddy validate --config "$CADDYFILE" --adapter caddyfile >/dev/null 2>&1) \
    || die "caddy validate failed"
  systemctl reload "$CADDY_UNIT"
}

start_step () {
  say "start $U_RELAY $U_WEB $U_SATURN"
  systemctl restart "$U_RELAY" "$U_WEB"
  systemctl restart "$U_SATURN"
  sleep 3
  local u; for u in "$U_RELAY" "$U_WEB" "$U_SATURN"; do systemctl is-active --quiet "$u" || die "$u did not start (journalctl -u $u)"; done
}

stop_step () { systemctl stop "$U_ACT" "$T_SCHED" "$U_SATURN" "$U_WEB" "$U_RELAY" 2>/dev/null || true; }

status_step () {
  local u
  for u in "$U_EGRESS" "$U_WEB" "$U_RELAY" "$U_SATURN" "$T_SCHED" "$U_ACT" "postgresql@15-$PG_CLUSTER"; do
    printf '%-34s enabled=%-9s active=%s\n' "$u" "$(systemctl is-enabled "$u" 2>/dev/null || true)" "$(systemctl is-active "$u" 2>/dev/null || true)"
  done
  [ -s "$ETC/hostname" ] && echo "url: https://$SITE_PREFIX$(cat "$ETC/hostname")/"
  ss -ltnH "sport = :$PORT" | awk '{print "listen", $4}'
  [ -x "$CLI" ] && "$CLI" saturn status || true
  du -sh "$OPT" "$WWW" "$HOMED" 2>/dev/null || true
}

teardown_step () {
  say "teardown: bc19 units, CLI, Caddy site (2023 untouched)"
  systemctl disable --now "$U_ACT" "$T_SCHED" "$U_SATURN" "$U_WEB" "$U_RELAY" 2>/dev/null || true
  rm -f "/etc/systemd/system/"{$U_WEB,$U_RELAY,$U_SATURN,$U_ACT,$U_SCHED,$T_SCHED} "$CLI"
  rm -f "/etc/systemd/system/$CADDY_UNIT.d/bc19-galaxy.conf" "$CADDY_SITE"
  sed -i "\#^import $CADDY_SITE\$#d; \#^\# bc19 galaxy replica#d" "$CADDYFILE"
  systemctl daemon-reload; systemctl reload "$CADDY_UNIT" || true
  if [ "${1:-}" = --purge-data ]; then
    systemctl disable --now "$U_EGRESS" 2>/dev/null || true; rm -rf "/etc/systemd/system/$U_EGRESS" "/etc/systemd/system/$SLICE" /etc/systemd/system/bc19.slice.d
    pg_dropcluster --stop 15 "$PG_CLUSTER" || true
    rm -rf "$HOMED" "$WWW" "$OPT" "$ETC" "$LIB"; userdel -r "$RUSER" 2>/dev/null || true
    systemctl daemon-reload
  fi
}

step="${1:-}"; shift || true
case "$step" in
  all)
    stage="${1:?stage dir}"
    user_step; egress_step; postgres_step; opt_step; app_step "$stage"; runtime_step "$stage"; dirs_step; secrets_step
    password_step; env_step; units_step; cli_step; migrate_step; bootstrap_step; static_step; viewer_step; frontend_step
    hostname_step; site_step; start_step; status_step ;;
  user) user_step ;; egress) egress_step ;; postgres) postgres_step ;; opt) opt_step ;;
  app) app_step "${1:?stage}" ;; runtime) runtime_step "${1:?stage}" ;; dirs) dirs_step ;; secrets) secrets_step ;;
  password) password_step ;; env) env_step ;; units) units_step ;; cli) cli_step ;; migrate) migrate_step ;;
  bootstrap) bootstrap_step ;; static) static_step ;; viewer) viewer_step ;; frontend) frontend_step ;;
  hostname) hostname_step ;; site) site_step ;; start) start_step ;; stop) stop_step ;; status) status_step ;;
  ensure-import) ensure_import ;;
  activity) case "${1:-}" in on) systemctl enable --now "$U_ACT" ;; off) systemctl disable --now "$U_ACT" ;; *) die "activity on|off" ;; esac ;;
  scheduler) case "${1:-}" in on) systemctl enable --now "$T_SCHED" ;; off) systemctl disable --now "$T_SCHED" ;; *) die "scheduler on|off" ;; esac ;;
  teardown) teardown_step "${1:-}" ;;
  *) sed -n '2,12p' "$0" >&2; exit 2 ;;
esac
