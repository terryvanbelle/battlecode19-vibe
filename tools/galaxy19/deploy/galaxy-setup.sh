#!/usr/bin/env bash
# Root-side setup of the bc19 galaxy replica on battlecode-dev (Debian 12), alongside the 2023 replica (whose files,
# units, user, database and nftables table are never modified; the one shared piece is the Caddy process, which gets
# an `import` line for the bc19 site). Every step is idempotent. Run by tools/galaxy19/deploy/deploy.sh from the
# driver; doc: tools/galaxy19/README.md.
#
#   sudo galaxy-setup.sh all STAGE      every step below, STAGE = the pushed copy of the 2019 repo (tools/galaxy19,
#                                       tools/run_game.js, engine/, bots not needed); the viewer's pinned inputs
#                                       (official visualizer + images, pixi.js) are in $VIEWER_IN
#   sudo galaxy-setup.sh user | egress | postgres | opt | app STAGE | runtime STAGE | dirs | secrets | password | env
#   sudo galaxy-setup.sh units | cli | migrate | bootstrap | static | viewer | frontend | hostname | site | start
#   sudo galaxy-setup.sh stop | status | teardown [--purge-data] | scheduler on|off | activity on|off
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOC=/home/terryvanbelle/projects/vibe/2019/tools/galaxy19/README.md
OPERATOR=terryvanbelle
RUSER=bc19replica                         # runs every bc19 service; loopback-only network (nftables + slice)
OPT=/opt/bc19-galaxy                      # root-owned: src/ (siarnaq), venv/, galaxy19/ (our code), runtime/ (engine)
WWW=/srv/bc19-galaxy                      # root:caddy: frontend/ viewer/ static/ storage/
HOMED=/home/$RUSER/galaxy                 # bc19replica: secrets/ spool/ storage-meta/ saturn/ run/
ETC=/etc/bc19-galaxy
ENVF=$ETC/galaxy.env
LIB=/usr/local/lib/bc19-galaxy
CLI=/usr/local/bin/bc19-galaxy-manage
PORT=8019                                 # siarnaq (gunicorn) on 127.0.0.1 only
PG_CLUSTER=bc19; PG_PORT=5419; DB=siarnaq19
NFT_TABLE=bc19_replica_egress
NFT_OFFICIAL=bc19_official_block          # host-wide: no process on this VM may reach the official contest's hosts
OFFICIAL_HOSTS="battlecode.org www.battlecode.org api.battlecode.org play.battlecode.org releases.battlecode.org"
OFFICIAL_IPS_KNOWN="34.160.107.126 185.199.108.153 185.199.109.153 185.199.110.153 185.199.111.153"  # 2026-10-21
SLICE=bc19-replica.slice
U_EGRESS=bc19-replica-egress.service
U_WEB=bc19-galaxy-web.service; U_RELAY=bc19-galaxy-relay.service; U_SATURN=bc19-galaxy-saturn.service
U_ACT=bc19-galaxy-activity.service       # field.py activity (operator): field teams challenge near-rated teams
U_SCHED=bc19-galaxy-scheduler.service; T_SCHED=bc19-galaxy-scheduler.timer   # Cloud Scheduler stand-in (autoscrim)
VIEWER_IN=/home/terryvanbelle/projects/vibe/bc19-viewer-inputs   # battlecode19/ (official app files), pixi-4.8.9/
SRC23=/opt/bc23-galaxy                    # copied (read only) for siarnaq's source and venv: same pinned version
FRONT23=/srv/bc23-galaxy/frontend         # galaxy's built frontend (same-origin API), copied and patched for bc19
CADDYFILE=/etc/caddy/Caddyfile
CADDY_SITE=/etc/caddy/bc19-galaxy.caddy
CADDY_UNIT=bc23-replica-caddy.service
PASSWORD_FILE=$ETC/owner-password         # root 600: basic-auth gate + siarnaq superuser "owner"
SITE_PREFIX=galaxy19.
CSP="default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; frame-src 'self'; worker-src 'self' blob:; manifest-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'self'"
die () { echo "galaxy-setup: $*" >&2; exit 1; }
say () { echo "== $*"; }
[ "$(id -u)" = 0 ] || die "run as root (sudo)"
[ "$(hostname -s)" = battlecode-dev ] || die "this is $(hostname -s), not battlecode-dev"
as_r () { (cd / && runuser -u "$RUSER" -- "$@"); }

user_step () {
  say "user $RUSER (system, locked, nologin)"
  id -u "$RUSER" >/dev/null 2>&1 || useradd --system --user-group --home-dir "/home/$RUSER" --create-home \
    --shell /usr/sbin/nologin --comment "bc19 galaxy replica (no credentials, loopback-only network)" "$RUSER"
  passwd -l "$RUSER" >/dev/null 2>&1 || true
  chmod 0750 "/home/$RUSER"
}

egress_step () {
  local uid; uid=$(id -u "$RUSER")
  say "egress table inet $NFT_TABLE: uid $uid may use loopback port $PORT only; slice $SLICE"
  install -d -m 0755 "$ETC"
  cat > "$ETC/egress.nft.new" <<EOF
#!/usr/sbin/nft -f
# Egress lockdown for uid $uid ($RUSER), the bc19 galaxy replica. Generated by $LIB/galaxy-setup.sh; loaded at boot by
# $U_EGRESS. Touches only this table. Doc: $DOC
table inet $NFT_TABLE
delete table inet $NFT_TABLE
table inet $NFT_TABLE {
	chain output {
		type filter hook output priority filter - 10; policy accept;
		meta skuid $uid jump replica comment "$RUSER"
	}
	chain replica {
		ip daddr 169.254.169.254 counter drop comment "GCE metadata server"
		ip6 daddr fd20:ce::254 counter drop comment "GCE metadata server (IPv6)"
		oifname != "lo" limit rate 6/minute burst 5 packets log prefix "bc19-replica-egress-drop: " level info
		oifname != "lo" counter drop comment "no off-host egress"
		ct state established,related accept comment "replies on loopback"
		tcp dport $PORT accept comment "bc19 siarnaq"
		counter drop comment "no other loopback service (DNS stub, MTA, Caddy admin, the 2023 replica)"
	}
}
EOF
  # host-wide block of the official contest (every user, not only the replica's): the addresses its host names resolve
  # to now plus the ones recorded on 2026-10-21 (battlecode.org is GitHub Pages: those 4 addresses also serve other
  # *.github.io sites, which this VM does not need)
  local ips h
  ips="$OFFICIAL_IPS_KNOWN"
  for h in $OFFICIAL_HOSTS; do ips="$ips $(getent ahostsv4 "$h" 2>/dev/null | awk '{print $1}' | sort -u | tr '\n' ' ')"; done
  ips=$(echo $ips | tr ' ' '\n' | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | sort -u | paste -sd, -)
  cat >> "$ETC/egress.nft.new" <<EOF
# Every process on this VM: no packet to the official Battlecode hosts ($OFFICIAL_HOSTS).
table inet $NFT_OFFICIAL
delete table inet $NFT_OFFICIAL
table inet $NFT_OFFICIAL {
	set official {
		type ipv4_addr
		elements = { $ips }
	}
	chain output {
		type filter hook output priority filter - 20; policy accept;
		ip daddr @official limit rate 6/minute burst 5 packets log prefix "bc19-official-block: " level info
		ip daddr @official counter reject comment "official Battlecode hosts"
	}
}
EOF
  mv -f "$ETC/egress.nft.new" "$ETC/egress.nft"
  cat > "/etc/systemd/system/$U_EGRESS" <<EOF
[Unit]
Description=bc19 replica: egress lockdown for user $RUSER (loopback port $PORT only, metadata server dropped)
Documentation=file://$DOC
DefaultDependencies=no
Wants=network-pre.target
Before=network-pre.target shutdown.target
After=local-fs.target nftables.service
Conflicts=shutdown.target
PartOf=nftables.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $ETC/egress.nft
ExecReload=/usr/sbin/nft -f $ETC/egress.nft
ExecStop=-/usr/sbin/nft delete table inet $NFT_TABLE
ExecStop=-/usr/sbin/nft delete table inet $NFT_OFFICIAL

[Install]
WantedBy=sysinit.target
EOF
  cat > "/etc/systemd/system/$SLICE" <<EOF
[Unit]
Description=bc19 replica services (IP traffic limited to localhost; second layer behind $U_EGRESS)
Documentation=file://$DOC

[Slice]
IPAddressDeny=any
IPAddressAllow=localhost
EOF
  # replica games keep their CPU when the main session's batches (timescale 2, user.slice, weight 100) load the VM: a
  # robot's code load has a wall-clock budget, and big transpiled bundles fail it on a contended VM. The weight sits on
  # the parent bc19.slice, the level that competes with user.slice; saturn's CPUQuota still caps games at 3 cores.
  install -d -m 0755 /etc/systemd/system/bc19.slice.d
  printf '[Slice]\nCPUWeight=400\n' > /etc/systemd/system/bc19.slice.d/cpu-weight.conf
  systemctl daemon-reload
  systemctl enable --quiet "$U_EGRESS"
  systemctl restart "$U_EGRESS"
  nft list table inet "$NFT_TABLE" >/dev/null
  nft list table inet "$NFT_OFFICIAL" >/dev/null
}

postgres_step () {
  say "postgres cluster 15/$PG_CLUSTER on unix socket port $PG_PORT (no TCP), role $RUSER, database $DB"
  if ! pg_lsclusters -h | awk '{print $1"/"$2}' | grep -qx "15/$PG_CLUSTER"; then
    pg_createcluster 15 "$PG_CLUSTER" --port "$PG_PORT" -- --auth-local=peer >/dev/null
  fi
  local conf=/etc/postgresql/15/$PG_CLUSTER/conf.d/bc19-galaxy.conf
  printf '%s\n' "# bc19 galaxy replica: no TCP listener; small footprint" "listen_addresses = ''" \
    "shared_buffers = 64MB" "max_connections = 40" > "$conf.new"
  if ! cmp -s "$conf.new" "$conf"; then mv -f "$conf.new" "$conf"; systemctl restart "postgresql@15-$PG_CLUSTER"; else rm -f "$conf.new"; fi
  systemctl enable --quiet "postgresql@15-$PG_CLUSTER"
  systemctl is-active --quiet "postgresql@15-$PG_CLUSTER" || systemctl start "postgresql@15-$PG_CLUSTER"
  local psql=(runuser -u postgres -- psql -p "$PG_PORT" -tAq)
  [ "$("${psql[@]}" -c "SELECT 1 FROM pg_roles WHERE rolname='$RUSER'")" = 1 ] || "${psql[@]}" -c "CREATE ROLE $RUSER LOGIN"
  [ "$("${psql[@]}" -c "SELECT 1 FROM pg_database WHERE datname='$DB'")" = 1 ] || \
    "${psql[@]}" -c "CREATE DATABASE $DB OWNER $RUSER ENCODING 'UTF8' TEMPLATE template0"
  if ss -ltnH | awk '{print $4}' | grep -qE ":$PG_PORT\$"; then die "postgres listens on TCP $PG_PORT"; fi
}

opt_step () {
  say "siarnaq source + venv: copies of $SRC23/{src,venv} (same galaxy commit; 2023's stay untouched)"
  install -d -o root -g root -m 0755 "$OPT"
  local d
  for d in src venv; do
    if [ ! -e "$OPT/$d" ]; then
      [ -d "$SRC23/$d" ] || die "no $SRC23/$d to copy"
      rm -rf "$OPT/$d.new"; cp -a "$SRC23/$d" "$OPT/$d.new"; chown -R root:root "$OPT/$d.new"; mv "$OPT/$d.new" "$OPT/$d"
    fi
  done
  head -1 "$OPT/src/REPLICA_SOURCE" 2>/dev/null || true
  if find "$OPT/venv" -maxdepth 6 -path '*/site-packages/google*' | grep -q .; then die "a google package is in the venv"; fi
}

app_step () {  # $1 stage dir (repo copy)
  local stage="${1:?stage dir}"
  say "app: $stage/tools/galaxy19 -> $OPT/galaxy19 (root, read-only)"
  [ -f "$stage/tools/galaxy19/saturn.py" ] || die "no $stage/tools/galaxy19"
  rm -rf "$OPT/galaxy19.new"; cp -r "$stage/tools/galaxy19" "$OPT/galaxy19.new"
  find "$OPT/galaxy19.new" -name __pycache__ -prune -exec rm -rf {} +
  chown -R root:root "$OPT/galaxy19.new"; chmod -R go-w,a+rX "$OPT/galaxy19.new"
  rm -rf "$OPT/galaxy19.old"; [ -e "$OPT/galaxy19" ] && mv "$OPT/galaxy19" "$OPT/galaxy19.old"
  mv "$OPT/galaxy19.new" "$OPT/galaxy19"; rm -rf "$OPT/galaxy19.old"
  install -d -m 0755 "$LIB"; install -m 0755 "$HERE/galaxy-setup.sh" "$LIB/galaxy-setup.sh"
}

runtime_step () {  # $1 stage dir
  local stage="${1:?stage dir}" rt="$OPT/runtime"
  say "runtime: node, run_game.js, compile19.js, engine (bc19 $(sed -n 's/.*"version": "\(.*\)".*/\1/p' "$stage/engine/node_modules/bc19/package.json"))"
  [ -f "$stage/tools/run_game.js" ] && [ -d "$stage/engine/node_modules/bc19" ] || die "stage lacks run_game.js or the engine"
  rm -rf "$rt.new"; install -d -m 0755 "$rt.new" "$rt.new/bin" "$rt.new/tools" "$rt.new/engine"
  install -m 0755 "/home/$OPERATOR/bin/node" "$rt.new/bin/node"
  install -m 0644 "$stage/tools/run_game.js" "$stage/tools/galaxy19/compile19.js" "$rt.new/tools/"
