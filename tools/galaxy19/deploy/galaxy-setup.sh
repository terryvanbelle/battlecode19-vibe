cli_step () {
  cat > "$CLI.new" <<EOF
#!/usr/bin/env bash
# siarnaq's manage.py and the bc19 replica tools as $RUSER with the units' environment. Doc: $DOC
#   bc19-galaxy-manage <manage.py command ...> | bootstrap <cmd> | relay status|fire-jobs | saturn status
set -euo pipefail
ENV_FILE=$ENVF; RUN_AS=$RUSER; NFT_TABLE=$NFT_TABLE; PY=$OPT/venv/bin/python; BACKEND=$OPT/src/backend; APP=$OPT/galaxy19
EOF
  cat >> "$CLI.new" <<'EOF'
sudo -n /usr/sbin/nft list table inet "$NFT_TABLE" >/dev/null 2>&1 || { echo "egress table $NFT_TABLE not loaded; refusing" >&2; exit 1; }
mapfile -t envs < <(grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$ENV_FILE")
case "${1:-}" in
  bootstrap) shift; set -- "$APP/bootstrap.py" "$@" ;;
  relay) shift; PY=/usr/bin/python3; set -- "$APP/relay.py" "$@" ;;
  saturn) shift; PY=/usr/bin/python3; set -- "$APP/saturn.py" "$@" ;;
  '') echo "usage: bc19-galaxy-manage <manage.py command> | bootstrap ... | relay ... | saturn ..." >&2; exit 2 ;;
  *) set -- "$BACKEND/manage.py" "$@" ;;
esac
cd "$BACKEND"
exec sudo -u "$RUN_AS" env -i PATH=/usr/local/bin:/usr/bin:/bin HOME="/home/$RUN_AS" "${envs[@]}" "$PY" "$@"
EOF
  chmod 0755 "$CLI.new"; mv -f "$CLI.new" "$CLI"
  say "installed $CLI"
}

