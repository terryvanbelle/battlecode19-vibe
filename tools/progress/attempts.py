#!/usr/bin/env python3
"""The attempts ledger: every bot attempt, what it changes and its score at each stage of the acceptance funnel
(ported from battlecode23-vibe's tools/attempts.py). progress/attempts.csv is the source (one row per attempt);
progress/ATTEMPTS.md is rendered from it, with a "Recorded games" column computed from progress/games.csv.

  tools/progress/attempts.py set <codename> field=value ...   add or update a row ('field+=value' appends with '; ')
  tools/progress/attempts.py render                            write progress/ATTEMPTS.md
  tools/progress/attempts.py check                             list our players in games.csv with no row (exit 1)
  tools/progress/attempts.py refresh                           render + check (tools/progress-refresh.sh)

Fields: COLUMNS. `build` is the attempt's player name in games.csv (us:v3 for h1, which was accepted as v3; cand:h2
for a candidate bundle dist/h2; spar:rush); empty means cand:<codename>. Outcome words that the totals understand:
ACCEPTED ..., REJECTED ..., DROPPED ..., in progress, queued, sparring.
"""
import collections
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import elolib  # noqa: E402

CSV = os.path.join(elolib.PROGRESS, 'attempts.csv')
MD = os.path.join(elolib.PROGRESS, 'ATTEMPTS.md')
COLUMNS = ['codename', 'date', 'base', 'build', 'description', 'h2h', 'reference', 'replica', 'outcome', 'sources']
SHOWN = [('codename', 'Codename'), ('date', 'Built (PDT)'), ('base', 'Base'), ('description', 'What it changes'),
         ('h2h', 'Local h2h vs incumbent'), ('reference', 'Reference batches'), ('replica', 'Replica'),
         ('games', 'Recorded games (auto)'), ('outcome', 'Outcome')]


def load(path=CSV):
    if not os.path.exists(path):
        return []
    with open(path, newline='') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for c in COLUMNS:
            r[c] = (r.get(c) or '').strip()
    return rows


def save(rows, path=CSV):
    rows = sorted(rows, key=lambda r: (r['date'] or '9999', r['codename']))
    with open(path + '.tmp', 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS, lineterminator='\n')
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, '') for c in COLUMNS})
    os.replace(path + '.tmp', path)


def set_fields(rows, name, assigns):
    r = next((r for r in rows if r['codename'] == name), None)
    if r is None:
        r = {c: '' for c in COLUMNS}
        r['codename'] = name
        rows.append(r)
    for a in assigns:
        i = a.find('=')
        if i <= 0:
            raise SystemExit(f'attempts: bad assignment {a!r} (field=value or field+=value)')
        append = a[i - 1] == '+'
        k, v = (a[:i - 1] if append else a[:i]).strip(), a[i + 1:].strip()
        if k not in COLUMNS or k == 'codename':
            raise SystemExit(f'attempts: unknown field {k!r} (fields: {", ".join(COLUMNS[1:])})')
        r[k] = f'{r[k]}; {v}' if append and r[k] and v else (v if not append else r[k] or v)
    return r


def player_of(r):
    return r['build'] or f"cand:{r['codename']}"


def games_cell(player, games_rows):
    """'vs v2 27-9; vs bc19-starter 3-0 (replica)': the player's W-L against each opponent, most games first."""
    rec = collections.defaultdict(lambda: [0, 0, set()])
    for g in games_rows:
        for me, opp, side in ((g['teamA'], g['teamB'], 'A'), (g['teamB'], g['teamA'], 'B')):
            if me == player and opp != player:
                x = rec[opp]
                x[0] += g['winner'] == side
                x[1] += 1
                x[2].add('replica' if elolib.is_replica(g) else 'local')
    parts = []
    for opp, (w, n, where) in sorted(rec.items(), key=lambda kv: (-kv[1][1], kv[0])):
        tag = '' if where == {'local'} else ' (replica)' if where == {'replica'} else ' (local+replica)'
        parts.append(f'vs {elolib.build_of(opp)} {w}-{n - w}{tag}')
    return '; '.join(parts)


def kind(outcome):
    o = outcome.upper()
    for k, text in (('ACCEPTED', 'accepted'), ('REJECTED', 'rejected'), ('DROPPED', 'dropped'),
                    ('IN PROGRESS', 'in progress'), ('QUEUED', 'queued'), ('SPARRING', 'sparring partners')):
        if o.startswith(k):
            return text
    return 'other'


def esc(s):
    return s.replace('|', '\\|').replace('\n', ' ')


def render(rows, games_rows, path=MD):
    rows = sorted(rows, key=lambda r: (r['date'] or '9999', r['codename']))
    kinds = collections.Counter(kind(r['outcome']) for r in rows)
    lines = [
        '# Attempts', '',
        'Every bot attempt, oldest first, with its score at each stage of the acceptance funnel. Generated by '
        '`tools/progress/attempts.py render` from `progress/attempts.csv`; update a row with '
        '`tools/progress/attempts.py set <codename> field=value ...`, never by editing this file.', '',
        '**The funnel** (TRAINING_ALGORITHM.md §2):',
        '1. **Local h2h vs incumbent**: the candidate against the accepted build on random map seeds, both sides, on '
        'the VM (`tools/batch.js`, timescale 2 since v3; round-0 init failures retried, not counted).',
        '2. **Reference batches**: the same against fixed references (the starter bot `bots/example`, older builds, '
        'sparring partners) as a screen.',
        '3. **Replica**: submitted to the galaxy replica (`tools/galaxy19/contest19.py submit`); its games there '
        '(`progress/ELO.md`, `progress/rating-history.md`).',
        '4. **Outcome**: accepted (the roster name it was frozen as), rejected, dropped, in progress, queued; '
        'sparring partners are training opponents, not attempts at the bot.', '',
        '**Recorded games (auto)** is computed at each render from `progress/games.csv`: the attempt\'s W-L against '
        'every opponent (local unless marked replica), under its player name (`build`; candidates are '
        '`cand:<codename>`). It includes batches still running at the last refresh.', '',
        'Totals: ' + ', '.join(f'{v} {k}' for k, v in sorted(kinds.items(), key=lambda kv: (-kv[1], kv[0])))
        + f' ({len(rows)} rows).', '',
        '| ' + ' | '.join(h for _, h in SHOWN) + ' |',
        '|' + '|'.join('---' for _ in SHOWN) + '|']
    for r in rows:
        cells = [esc(games_cell(player_of(r), games_rows) if k == 'games' else r[k]) for k, _ in SHOWN]
        cells[0] = f'`{cells[0]}`' + (f" ({elolib.build_of(r['build'])})" if r['build'].startswith('us:')
                                      and elolib.build_of(r['build']) != r['codename'] else '')
        lines.append('| ' + ' | '.join(cells) + ' |')
    with open(path + '.tmp', 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    os.replace(path + '.tmp', path)


def missing(rows, games_rows):
    """Our players (us:/cand:/spar:) with games but no attempts row."""
    have = {player_of(r) for r in rows}
    seen = {t for g in games_rows for t in (g['teamA'], g['teamB']) if not elolib.is_field(t)}
    return sorted(seen - have)


def main(argv):
    if not argv or argv[0] in ('-h', '--help'):
        print(__doc__)
        return 0
    cmd, rest = argv[0], argv[1:]
    rows, games_rows = load(), elolib.load()
    if cmd == 'set':
        if len(rest) < 2:
            raise SystemExit('usage: tools/progress/attempts.py set <codename> field=value ...')
        set_fields(rows, rest[0], rest[1:])
        save(rows)
        render(load(), games_rows)
        return 0
    if cmd in ('render', 'refresh'):
        render(rows, games_rows)
        print(f'wrote {os.path.relpath(MD, elolib.REPO)} ({len(rows)} attempts)')
        if cmd == 'render':
            return 0
    if cmd in ('check', 'refresh'):
        miss = missing(rows, games_rows)
        if miss:
            print(f'!! players in games.csv with no attempts row: {" ".join(miss)} '
                  f'(add one: tools/progress/attempts.py set <codename> build=<player> ...)')
            return 1
        print('attempts: every player of ours in games.csv has a row')
        return 0
    raise SystemExit(f'attempts: unknown command {cmd!r}')


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
